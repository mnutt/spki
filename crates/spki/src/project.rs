use anyhow::{Context, Result, ensure};
use serde::Deserialize;
use serde_json::Value;
use std::{
    fs,
    path::{Path, PathBuf},
};
include!(concat!(env!("OUT_DIR"), "/schemas.rs"));
const CONFIG: &str = "sandstorm-pkgdef.capnp";
#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Project {
    format_version: u16,
    worker: Worker,
    compatibility_date: String,
    #[serde(default)]
    compatibility_flags: Vec<String>,
    runtime: Runtime,
    compiler: Compiler,
    preview: Preview,
    #[serde(default)]
    ui: Ui,
    #[serde(default)]
    assets: Vec<String>,
    #[serde(default)]
    schemas: Vec<String>,
    #[serde(default)]
    bindings: Vec<Binding>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Worker {
    entrypoint: String,
}
#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Runtime {
    release: String,
    host_sha256: String,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Compiler {
    version: String,
    name: String,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Preview {
    profile: String,
    #[serde(default)]
    project: String,
}
#[derive(Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct Ui {
    #[serde(default)]
    entrypoints: Vec<String>,
}
#[derive(Clone, Deserialize)]
struct Binding {
    name: String,
    #[serde(flatten)]
    value: BindingValue,
}
#[derive(Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
enum BindingValue {
    Text(String),
    Json(String),
    DataFile(String),
    Service(String),
}
#[derive(Clone)]
pub struct Settings {
    bindings: Vec<Binding>,
    pub entry: PathBuf,
    pub root: PathBuf,
    pub ui: Vec<PathBuf>,
    pub assets: Vec<PathBuf>,
    pub schemas: Vec<PathBuf>,
    pub profile: String,
    pub project: String,
}
pub fn discover(explicit: Option<&Path>) -> Result<Option<PathBuf>> {
    if let Some(path) = explicit {
        let path = if path.is_dir() {
            path.join(CONFIG)
        } else {
            path.to_owned()
        };
        return Ok(Some(
            fs::canonicalize(path).context("project configuration not found")?,
        ));
    }
    let cwd = std::env::current_dir()
        .context("current directory was removed or is inaccessible; run cd \"$PWD\" and retry")?;
    for dir in cwd.ancestors() {
        let path = dir.join(CONFIG);
        if path.exists() {
            return Ok(Some(fs::canonicalize(path)?));
        }
    }
    Ok(None)
}
pub fn read(file: &Path) -> Result<Settings> {
    let imports = tempfile::tempdir()?;
    for (name, source) in SCHEMAS {
        let path = imports.path().join(name);
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, source)?;
    }
    let config = crate::capnp_compiler::Configuration::read(file, imports.path())?;
    let project: Project = serde_json::from_value(config.project()?)
        .context("invalid spki project fields")?;
    ensure!(
        project.format_version == 1,
        "unsupported spki formatVersion"
    );
    ensure!(
        project.compatibility_date == "2026-06-10" && project.compatibility_flags.is_empty(),
        "unsupported compatibility date or flags; this runtime requires 2026-06-10 with no flags"
    );
    ensure!(
        project.runtime.release == "0.1.2"
            && project.runtime.host_sha256 == spki_common::HOST_SHA256,
        "project runtime differs from this CLI"
    );
    ensure!(
        project.compiler.name == "rolldown" && project.compiler.version == crate::compiler::VERSION,
        "project compiler differs from this CLI; use compiler = (name = \"rolldown\", version = \"1.3.1\")"
    );
    super::store_path(&project.preview.profile)?;
    if !project.preview.project.is_empty() {
        spki_common::validate_id(&project.preview.project)?;
    }
    let pkg = config.package()?;
    ensure!(
        pkg["manifest"]["appTitle"]["defaultText"]
            .as_str()
            .is_some_and(|s| !s.is_empty()),
        "pkgdef requires an app title"
    );
    for reserved in ["sourceMap", "fileList", "alwaysInclude", "bridgeConfig"] {
        ensure!(
            pkg.get(reserved).is_none(),
            "pkgdef.{reserved} is not supported in authoring configuration yet"
        );
    }
    ensure!(
        pkg["manifest"].get("continueCommand").is_none(),
        "native commands are generated by spki; remove continueCommand"
    );
    if let Some(actions) = pkg["manifest"]["actions"].as_array() {
        for action in actions {
            ensure!(
                action.get("command").is_none(),
                "native commands are generated by spki; remove action.command"
            );
        }
    }
    let entry = Path::new(&project.worker.entrypoint);
    ensure!(
        !entry.as_os_str().is_empty()
            && !entry.is_absolute()
            && entry.components().all(|c| matches!(
                c,
                std::path::Component::Normal(_) | std::path::Component::CurDir
            )),
        "worker.entrypoint must be a project-relative path without '..'"
    );
    let root = file.parent().unwrap();
    let relative = |value: String| -> Result<PathBuf> {
        let path = PathBuf::from(value);
        ensure!(
            !path.as_os_str().is_empty()
                && path
                    .components()
                    .all(|c| matches!(c, std::path::Component::Normal(_))),
            "frontend paths must be project-relative without dot segments"
        );
        Ok(root.join(path))
    };
    Ok(Settings {
        bindings: project.bindings,
        root: root.to_owned(),
        schemas: project
            .schemas
            .into_iter()
            .map(relative)
            .collect::<Result<_>>()?,
        ui: project
            .ui
            .entrypoints
            .into_iter()
            .map(relative)
            .collect::<Result<_>>()?,
        assets: project
            .assets
            .into_iter()
            .map(relative)
            .collect::<Result<_>>()?,
        entry: root.join(entry),
        profile: project.preview.profile,
        project: project.preview.project,
    })
}
pub fn resolve(
    file: Option<&Path>,
    entry: Option<&Path>,
    profile: Option<&str>,
) -> Result<Settings> {
    let mut settings = if let Some(file) = file {
        read(file)?
    } else {
        Settings {
            bindings: Vec::new(),
            root: std::env::current_dir()?,
            ui: Vec::new(),
            assets: Vec::new(),
            schemas: Vec::new(),
            entry: entry
                .context("no project configuration; run spki init or specify --entry")?
                .to_owned(),
            profile: "default".into(),
            project: String::new(),
        }
    };
    if let Some(entry) = entry {
        settings.entry = entry.to_owned();
    }
    if let Some(profile) = profile {
        settings.profile = profile.to_owned();
    }
    Ok(settings)
}
pub fn init(target: &Path, profile: &str) -> Result<()> {
    super::store_path(profile)?;
    let target = std::path::absolute(target)?;
    let existing = target.exists();
    if existing {
        ensure!(
            target.is_dir() && fs::read_dir(&target)?.next().is_none(),
            "init requires a new or empty directory; existing files are never overwritten"
        );
    }
    let parent = target
        .parent()
        .context("cannot initialize filesystem root")?;
    ensure!(parent.is_dir(), "parent directory must already exist");
    let temporary = tempfile::tempdir_in(parent)?;
    let mut random = [0u8; 8];
    getrandom::fill(&mut random).context("generate schema ID")?;
    let id = format!("@0x{:016x}", u64::from_le_bytes(random) | (1 << 63));
    let version = crate::compiler::VERSION;
    let name: String = target
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .take(40)
        .collect();
    let project_id = format!("{}-{}", name, &id[3..11]);
    let config = format!(
        r#"{id};
using Spk = import "/sandstorm/package.capnp";
using Spki = import "/spki/project.capnp";
# Authoring template. Set id from spki keygen before packaging; native commands are generated.
const pkgdef :Spk.PackageDefinition = (
  manifest = (
    appTitle = (defaultText = "My isolate"), appVersion = 1,
    appMarketingVersion = (defaultText = "0.1.0"),
    actions = [(input = (none = void), nounPhrase = (defaultText = "document"))]
  )
);
const spki :Spki.Project = (
  formatVersion = 1,
  worker = (entrypoint = "src/worker.ts"),
  compatibilityDate = "2026-06-10", compatibilityFlags = [],
  runtime = (release = "0.1.2", hostSha256 = "{host}"),
  compiler = (version = "{version}", name = "rolldown"),
  preview = (profile = "{profile}", project = "{project_id}")
);
"#,
        host = spki_common::HOST_SHA256,
        version = version
    );
    fs::write(temporary.path().join(CONFIG), config)?;
    fs::create_dir(temporary.path().join("src"))?;
    fs::write(
        temporary.path().join("src/worker.ts"),
        include_str!("../templates/worker.ts"),
    )?;
    fs::write(
        temporary.path().join("src/greeting.ts"),
        "export const greeting: string = 'Hello from your isolate';\n",
    )?;
    fs::write(
        temporary.path().join(".gitignore"),
        "dist/\n.spki/\nnode_modules/\n",
    )?;
    // Evaluate the template before publishing it, so a failed init leaves no partial project.
    read(&temporary.path().join(CONFIG))?;
    if existing {
        // Preserve the directory inode: the invoking shell may have this directory
        // as its cwd. Replacing it would break subsequent getcwd() calls.
        publish_into(temporary.path(), &target)?;
    } else {
        fs::rename(temporary.path(), &target)?;
    }
    println!(
        "Created {}\nNext: spki auth, then spki dev.\nFor local HTTP previews, use spki auth --allow-local-http.\nThe schema compiler and Rolldown bundler are built in.",
        target.display()
    );
    Ok(())
}

fn publish_into(source: &Path, target: &Path) -> Result<()> {
    ensure!(
        fs::read_dir(target)?.next().is_none(),
        "init target is no longer empty"
    );
    fn publish(source: &Path, target: &Path, created: &mut Vec<(PathBuf, bool)>) -> Result<()> {
        for entry in fs::read_dir(source)? {
            let entry = entry?;
            let destination = target.join(entry.file_name());
            let directory = entry.file_type()?.is_dir();
            if directory {
                fs::create_dir(&destination)?;
            } else {
                // Staging is on the same filesystem. Linking publishes each complete file
                // without overwriting anything another process may have created meanwhile.
                fs::hard_link(entry.path(), &destination)?;
            }
            created.push((destination.clone(), directory));
            if directory {
                publish(&entry.path(), &destination, created)?;
            }
        }
        Ok(())
    }
    let mut created = Vec::new();
    let result = publish(source, target, &mut created);
    if result.is_err() {
        for (path, directory) in created.into_iter().rev() {
            let _ = if directory {
                fs::remove_dir(path)
            } else {
                fs::remove_file(path)
            };
        }
    }
    result.context("could not populate existing project directory")
}

// Native packing preserves all original manifest fields, then supplies only generated commands.
pub fn package_metadata(file: &Path) -> Result<(Value, Vec<u8>)> {
    read(file)?;
    let imports = tempfile::tempdir()?;
    for (name, source) in SCHEMAS {
        let path = imports.path().join(name);
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, source)?;
    }
    let config = crate::capnp_compiler::Configuration::read(file, imports.path())?;
    Ok((config.package()?, config.manifest()?))
}

impl Settings {
    fn binding_path(&self, value: &str) -> Result<PathBuf> {
        let path = Path::new(value);
        ensure!(
            !value.is_empty()
                && path
                    .components()
                    .all(|p| matches!(p, std::path::Component::Normal(_))),
            "binding dataFile must be project-relative without dot segments"
        );
        Ok(self.root.join(path))
    }
    pub fn binding_paths(&self) -> Result<Vec<PathBuf>> {
        self.bindings
            .iter()
            .filter_map(|binding| match &binding.value {
                BindingValue::DataFile(path) => Some(self.binding_path(path)),
                _ => None,
            })
            .collect()
    }
    pub fn bindings(
        &self,
        inputs: &mut std::collections::BTreeSet<PathBuf>,
    ) -> Result<Vec<spki_common::bindings::Binding>> {
        use base64::{Engine, engine::general_purpose::STANDARD};
        use spki_common::bindings::{Binding as Native, Value};
        let mut output = Vec::new();
        ensure!(
            self.bindings.len() <= 64,
            "at most 64 custom bindings are allowed"
        );
        for binding in &self.bindings {
            let value = match &binding.value {
                BindingValue::Text(value) => Value::Text(value.clone()),
                BindingValue::Json(value) => Value::Json(value.clone()),
                BindingValue::Service(value) => Value::Service(value.clone()),
                BindingValue::DataFile(value) => {
                    inputs.insert(self.binding_path(value)?);
                    let path = Path::new(value);
                    let mut file = self.root.clone();
                    for component in path.components() {
                        file.push(component);
                        ensure!(
                            !fs::symlink_metadata(&file)?.file_type().is_symlink(),
                            "binding dataFile cannot use symlinks"
                        );
                    }
                    let metadata = fs::metadata(&file)?;
                    ensure!(
                        metadata.is_file()
                            && metadata.len() <= spki_common::bindings::MAX_VALUE as u64,
                        "binding dataFile must be a regular file no larger than 1 MiB"
                    );
                    use std::io::Read;
                    let mut data = Vec::new();
                    fs::File::open(file)?
                        .take(spki_common::bindings::MAX_VALUE as u64 + 1)
                        .read_to_end(&mut data)?;
                    ensure!(
                        data.len() <= spki_common::bindings::MAX_VALUE,
                        "binding dataFile exceeds 1 MiB"
                    );
                    Value::Data(STANDARD.encode(data))
                }
            };
            output.push(Native {
                name: binding.name.clone(),
                value,
            });
        }
        spki_common::bindings::validate(&output)?;
        Ok(output)
    }
}
