//! Maintainer helper, invoked by tools/schema-compiler/generate-embedded.py.
use anyhow::{Result, ensure};
use rolldown::{Bundler, BundlerOptions, OutputFormat, Platform, RawMinifyOptions};
#[tokio::main]
async fn main() -> Result<()> {
    let args: Vec<_> = std::env::args().collect();
    ensure!(
        args.len() == 3,
        "usage: bundle-schema-compiler ENTRY OUTPUT"
    );
    let mut bundler = Bundler::new(BundlerOptions {
        input: Some(vec![args[1].clone().into()]),
        platform: Some(Platform::Neutral),
        format: Some(OutputFormat::Iife),
        minify: Some(RawMinifyOptions::Bool(true)),
        ..Default::default()
    })
    .map_err(|e| anyhow::anyhow!("{e:?}"))?;
    let output = bundler
        .generate()
        .await
        .map_err(|e| anyhow::anyhow!("{e:?}"))?;
    ensure!(output.warnings.is_empty(), "{:?}", output.warnings);
    ensure!(
        output.assets.len() == 1,
        "expected one self-contained compiler bundle"
    );
    let code = output.assets[0].content_as_bytes();
    let mut source = b"/*! capnp-es 0.3.0 generator and runtime; MIT; see LICENSE. Generated by tools/schema-compiler/generate-embedded.py. */\n".to_vec();
    source.extend_from_slice(code);
    std::fs::write(&args[2], source)?;
    Ok(())
}
